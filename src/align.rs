/// Gap-open penalty. Calibrated in the reference; not a knob.
pub const GAP_OPEN: f64 = -12.0;
/// Gap-extend penalty.
pub const GAP_EXTEND: f64 = -1.0;

/// Far enough below any reachable score to act as −inf without producing NaN on addition.
const NEG: f64 = -1.0e18;

/// Fold one residue byte onto its `BLOSUM62` row, uppercasing and sending anything unrecognised
/// to `X` — the same folding the reference's matrix lookup performs.
#[inline]
fn encode_byte(byte: u8) -> u8 {
    let upper = byte.to_ascii_uppercase();
    match ALPHA.iter().position(|&c| c == upper) {
        Some(index) => index as u8,
        None => X_INDEX,
    }
}

/// Encode a sequence into `BLOSUM62` row indices.
///
/// Callers encode a reference once and reuse it across queries; `regions.rs` encodes the 15 gene
/// reference precursors at table-load time for exactly that reason.
pub fn encode(sequence: &[u8]) -> Vec<u8> {
    sequence.iter().map(|&b| encode_byte(b)).collect()
}

/// The traceback state, in the preference order the tie-break uses.
#[derive(Clone, Copy, PartialEq, Eq)]
enum State {
    /// Match/mismatch: consumes one reference and one query residue.
    Match,
    /// Gap in the query: consumes a reference residue only.
    RefGap,
    /// Gap in the reference: consumes a query residue only.
    QueryGap,
}

/// One global alignment of a query against a reference.
pub struct Alignment {
    /// `query_to_reference[i]` is the 1-based reference position paired with query residue `i`, or
    /// `None` where the alignment leaves that residue unpaired. An unpaired residue has no
    /// reference position, and inventing one would be a fabrication — so it is `None` rather than
    /// a nearby guess, and each caller decides what to do about it.
    pub query_to_reference: Vec<Option<u32>>,
    /// Fractional identity over paired positions.
    pub identity: f64,
    /// How many query residues received a reference position.
    pub n_mapped: usize,
    /// Internal gaps in **reference** numbering as inclusive `(start, end)` spans: the reference
    /// positions the query does not cover between its first and last paired residue. These are the
    /// disordered stretches that make the gapped alignment necessary, so they are reported rather
    /// than discarded (`histo_kir` numbering Rule 2).
    pub reference_gaps: Vec<(u32, u32)>,
    /// Alignment score, for checking against the reference implementation.
    /// Optimal alignment score. Not read by the transfer -- which needs the mapping, not its
    /// score -- but retained because it is the number to compare when checking parity against the
    /// reference aligner, and the parity test does exactly that.
    #[allow(dead_code)]
    pub score: f64,
}

impl Alignment {
    /// First query index paired to each 1-based reference position, or `-1` where the reference
    /// position is uncovered. Index 0 is unused so a reference position indexes directly.
    ///
    /// This is the inversion `histo_kir` performs as `ref_to_gene` / `mature_to_index`, and it is
    /// what a window transfer reads: a window is transferable only where *every* one of its
    /// reference positions is covered.
    pub fn reference_to_query(&self, reference_len: usize) -> Vec<i64> {
        let mut out = vec![-1i64; reference_len + 1];
        for (query_index, slot) in self.query_to_reference.iter().enumerate() {
            if let Some(position) = slot {
                let position = *position as usize;
                if position < out.len() && out[position] < 0 {
                    out[position] = query_index as i64;
                }
            }
        }
        out
    }
}

/// Globally align an encoded `query` against an encoded `reference` under BLOSUM62 with affine gaps.
///
/// Gotoh's three-plane recursion. Both arguments are `align::encode` output. End gaps are penalized
/// identically to internal gaps — see the module docstring for why that reproduces the reference
/// rather than departing from it.
pub fn align(reference: &[u8], query: &[u8]) -> Alignment {
    let (n, m) = (reference.len(), query.len());

    if n == 0 || m == 0 {
        return Alignment {
            query_to_reference: vec![None; m],
            identity: 0.0,
            n_mapped: 0,
            reference_gaps: Vec::new(),
            score: if n == 0 && m == 0 {
                0.0
            } else {
                GAP_OPEN + ((n.max(m) - 1) as f64) * GAP_EXTEND
            },
        };
    }

    let width = m + 1;
    let cells = (n + 1) * width;
    let mut mp = vec![NEG; cells];
    let mut ixp = vec![NEG; cells];
    let mut iyp = vec![NEG; cells];
    mp[0] = 0.0;
    for i in 1..=n {
        ixp[i * width] = GAP_OPEN + ((i - 1) as f64) * GAP_EXTEND;
    }
    for j in 1..=m {
        iyp[j] = GAP_OPEN + ((j - 1) as f64) * GAP_EXTEND;
    }

    for i in 1..=n {
        let row = i * width;
        let prev = (i - 1) * width;
        let sub_row = &BLOSUM62[reference[i - 1] as usize];
        for j in 1..=m {
            let diag = mp[prev + j - 1].max(ixp[prev + j - 1]).max(iyp[prev + j - 1]);
            mp[row + j] = diag + f64::from(sub_row[query[j - 1] as usize]);
            ixp[row + j] = (mp[prev + j] + GAP_OPEN)
                .max(ixp[prev + j] + GAP_EXTEND)
                .max(iyp[prev + j] + GAP_OPEN);
            iyp[row + j] = (mp[row + j - 1] + GAP_OPEN)
                .max(iyp[row + j - 1] + GAP_EXTEND)
                .max(ixp[row + j - 1] + GAP_OPEN);
        }
    }

    // Traceback. `State::Match` is tried first at every branch: that is the tie-break that
    // reproduces Biopython's `alignment[0]` on all 2037 measured cases.
    let end = n * width + m;
    let score = mp[end].max(ixp[end]).max(iyp[end]);
    let mut state = if mp[end] >= score {
        State::Match
    } else if ixp[end] >= score {
        State::RefGap
    } else {
        State::QueryGap
    };

    let mut query_to_reference = vec![None; m];
    let mut matched = 0usize;
    let mut paired = 0usize;
    let (mut i, mut j) = (n, m);
    // Float equality is the right test here: every candidate is recomputed by the same additions
    // that produced the stored cell, so an exact bit match is what identifies the predecessor.
    let close = |a: f64, b: f64| (a - b).abs() < 1e-9;

    while i > 0 || j > 0 {
        match state {
            State::Match => {
                debug_assert!(i > 0 && j > 0);
                query_to_reference[j - 1] = Some(i as u32);
                paired += 1;
                if reference[i - 1] == query[j - 1] {
                    matched += 1;
                }
                let target = mp[i * width + j]
                    - f64::from(BLOSUM62[reference[i - 1] as usize][query[j - 1] as usize]);
                let back = (i - 1) * width + (j - 1);
                i -= 1;
                j -= 1;
                state = if close(mp[back], target) {
                    State::Match
                } else if close(ixp[back], target) {
                    State::RefGap
                } else {
                    State::QueryGap
                };
            }
            State::RefGap => {
                debug_assert!(i > 0);
                let target = ixp[i * width + j];
                let back = (i - 1) * width + j;
                i -= 1;
                state = if close(mp[back] + GAP_OPEN, target) {
                    State::Match
                } else if close(ixp[back] + GAP_EXTEND, target) {
                    State::RefGap
                } else {
                    State::QueryGap
                };
            }
            State::QueryGap => {
                debug_assert!(j > 0);
                let target = iyp[i * width + j];
                let back = i * width + (j - 1);
                j -= 1;
                state = if close(mp[back] + GAP_OPEN, target) {
                    State::Match
                } else if close(iyp[back] + GAP_EXTEND, target) {
                    State::QueryGap
                } else {
                    State::RefGap
                };
            }
        }
    }

    // Internal reference gaps: covered reference positions between the first and last paired
    // residue that the query does not reach.
    let mut covered: Vec<u32> = query_to_reference.iter().flatten().copied().collect();
    covered.sort_unstable();
    let mut reference_gaps = Vec::new();
    for pair in covered.windows(2) {
        if pair[1] > pair[0] + 1 {
            reference_gaps.push((pair[0] + 1, pair[1] - 1));
        }
    }

    Alignment {
        query_to_reference,
        identity: if paired == 0 {
            0.0
        } else {
            matched as f64 / paired as f64
        },
        n_mapped: paired,
        reference_gaps,
        score,
    }
}
