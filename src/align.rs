//! Affine-gap global alignment, transcribed from what `histo_kir.numbering.align_to_reference`
//! actually does.
//!
//! This is a **transcription, not an improvement** (package invariant: the plugin is a performance
//! path, never a second implementation). Three details of the reference are reproduced deliberately,
//! and each one is load-bearing:
//!
//! * **BLOSUM62 with gap open −12 / extend −1.** The reference builds
//!   `Align.PairwiseAligner(scoring="blastp")`, which is BLOSUM62, and then sets those two
//!   penalties. The open penalty is calibrated so the aligner prefers a mismatch to inventing an
//!   indel — allelic variation is substitution, not indel — while still opening a gap for a
//!   genuinely disordered stretch (`histo_kir` numbering Rule 2).
//!
//! * **End gaps are penalized exactly as internal gaps are.** The reference's docstring says free
//!   end gaps, and it does assign `end_insertion_score = 0.0` / `end_deletion_score = 0.0` — but it
//!   then assigns `open_gap_score = -12.0`, and in Biopython that assignment writes *all four*
//!   terminal open scores as well, overwriting the zeros set two lines earlier. Measured on the live
//!   reference aligner: after the assignment, `open_left_insertion_score` is −12.0, not 0.0. So the
//!   effective behaviour is penalized end gaps, and that is what is reproduced here.
//!
//!   The divergence is real but small: across all 1983 IPD-KIR alleles, free end gaps would change
//!   28 of 13977 element windows, all on heavily-diverged or truncated alleles (chiefly
//!   `KIR2DS4*003*` and a handful of null alleles), and **0 of 378** windows on the 54 deposited
//!   chains. Parity with the reference is the contract, so the reference's actual behaviour wins.
//!   If the reference is ever fixed upstream, re-vendor and re-measure; do not "fix" it here.
//!
//! * **Match-state-first traceback.** Where several optimal alignments exist, the reported one
//!   depends on the traceback's tie-break. Biopython returns `alignment[0]`; preferring the match
//!   state, then the ref-consuming gap, then the query-consuming gap, reproduces its choice on
//!   **2037/2037** measured cases (1983 alleles + 54 deposited chains). 185 of the 1983 alleles have
//!   more than one optimal alignment, but only one — `KIR3DL3*080N`, a 34-residue null allele —
//!   has a tie whose two branches give *different* element windows, and match-first agrees with
//!   Biopython there too.

/// The alphabet the reference's substitution matrix is indexed by, in its own order.
